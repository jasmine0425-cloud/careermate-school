"""Small SQLite-style facade over PostgreSQL for the existing CareerMate routes.

All database parameters continue to be bound separately (no string-interpolated
user input). PostgreSQL identifiers containing capitals are quoted to preserve
the camelCase keys expected by the JSON endpoints.
"""
import re
import sqlite3
import psycopg
from psycopg.rows import dict_row

# SQLite tolerates double-quoted string literals; PostgreSQL does not.
_DOUBLE_QUOTED_ACTIVE = re.compile(r'(\baccountStatus\s*=\s*)"ACTIVE"')
_CAMEL_CASE_IDENTIFIER = re.compile(r'\b[a-z_][a-zA-Z0-9_]*[A-Z][a-zA-Z0-9_]*\b')
_AUTOINCREMENT = re.compile(r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b', re.I)
_INSERT = re.compile(r'^\s*INSERT\s', re.I)


def postgres_sql(sql):
    sql = _DOUBLE_QUOTED_ACTIVE.sub(r"\1'ACTIVE'", sql)
    sql = _AUTOINCREMENT.sub('INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
    # The legacy application uses mixed-case column names and SELECT aliases.
    sql = _CAMEL_CASE_IDENTIFIER.sub(lambda m: '"' + m.group(0) + '"', sql)
    return sql.replace('?', '%s')


class PgWriteResult:
    def __init__(self, rowcount, lastrowid=None):
        self.rowcount = rowcount
        self.lastrowid = lastrowid


class PostgresConnection:
    def __init__(self, url):
        self._conn = psycopg.connect(url, row_factory=dict_row, connect_timeout=10)

    def execute(self, sql, params=()):
        sql = postgres_sql(sql.strip())
        is_insert = bool(_INSERT.match(sql))
        if is_insert:
            # Each CareerMate INSERT inserts one row into an id-bearing table.
            sql = sql.rstrip(';') + ' RETURNING id'

        # Savepoints allow a duplicate INSERT to be caught without invalidating
        # the rest of the transaction (as happens with PostgreSQL by default).
        self._conn.execute('SAVEPOINT cm_statement')
        try:
            cursor = self._conn.cursor()
            cursor.execute(sql, tuple(params or ()))
            if is_insert:
                inserted = cursor.fetchone()
                output = PgWriteResult(cursor.rowcount, inserted['id'] if inserted else None)
                cursor.close()
            else:
                output = cursor
            self._conn.execute('RELEASE SAVEPOINT cm_statement')
            return output
        except Exception as exc:
            self._conn.execute('ROLLBACK TO SAVEPOINT cm_statement')
            self._conn.execute('RELEASE SAVEPOINT cm_statement')
            if isinstance(exc, psycopg.IntegrityError):
                raise sqlite3.IntegrityError(str(exc)) from exc
            raise

    def executescript(self, script):
        # Current CareerMate schema contains no semicolons inside SQL literals.
        for statement in script.split(';'):
            if statement.strip():
                result = self.execute(statement)
                if hasattr(result, 'close'):
                    result.close()

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        self._conn.close()
