"""SQLite for local development; PostgreSQL for durable hosted records.

The existing application uses qmark SQL and camelCase columns. This small
adapter preserves that contract while binding values with psycopg, quoting
camelCase identifiers, and recovering failed statements with savepoints.
"""
import re
import sqlite3
from urllib.parse import urlsplit

import psycopg
from psycopg.rows import dict_row

IntegrityError = (sqlite3.IntegrityError, psycopg.IntegrityError)
_TOKENS = re.compile(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|[A-Za-z_][A-Za-z_0-9]*|\?")


def postgres_sql(statement):
    """Translate only application-owned SQL; values remain bound parameters."""
    statement = re.sub(r'INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT',
                       'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
                       statement, flags=re.I)

    def token(match):
        value = match.group()
        if value == '?':
            return '%s'
        if value[0] in "'\"":
            return value
        if not value.isupper() and any(c.isupper() for c in value):
            return '"' + value + '"'
        return value

    return _TOKENS.sub(token, statement)


class PostgresCursor:
    def __init__(self, cursor, lastrowid=None):
        self.cursor = cursor
        self.lastrowid = lastrowid
        self.rowcount = cursor.rowcount

    def fetchone(self):
        return self.cursor.fetchone()

    def fetchall(self):
        return self.cursor.fetchall()


class PostgresConnection:
    def __init__(self, url):
        host = urlsplit(url).hostname
        # Remote databases require TLS; loopback is reserved for local tests.
        options = {} if host in ('localhost', '127.0.0.1', '::1') else {'sslmode': 'require'}
        self.connection = psycopg.connect(url, row_factory=dict_row,
                                         cursor_factory=psycopg.ClientCursor,
                                         connect_timeout=10, prepare_threshold=None,
                                         **options)
        self.connection.execute('SET search_path TO careermate, pg_catalog')

    def execute(self, statement, parameters=()):
        sql = postgres_sql(statement).rstrip().rstrip(';')
        insert = bool(re.match(r'\s*INSERT\s+INTO\s+', sql, re.I))
        if insert:
            sql += ' RETURNING id'
        # A duplicate row must not invalidate the rest of a CSV import or invite.
        self.connection.execute('SAVEPOINT careermate_statement')
        try:
            cursor = self.connection.execute(sql, tuple(parameters) if parameters else None)
            lastrowid = cursor.fetchone()['id'] if insert else None
        except Exception:
            self.connection.execute('ROLLBACK TO SAVEPOINT careermate_statement')
            raise
        finally:
            self.connection.execute('RELEASE SAVEPOINT careermate_statement')
        return PostgresCursor(cursor, lastrowid)

    def executescript(self, script):
        self.connection.execute('CREATE SCHEMA IF NOT EXISTS careermate')
        for statement in script.split(';'):
            if statement.strip():
                self.execute(statement)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def connect_database(path, url=''):
    if url:
        if not url.startswith(('postgres://', 'postgresql://')):
            raise RuntimeError('DATABASE_URL에는 PostgreSQL 연결 주소를 설정하세요.')
        return PostgresConnection(url)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    connection.execute('PRAGMA foreign_keys = ON')
    return connection
