"""SQL adapter regression tests. No live database connection is required."""
import unittest
from database import postgres_sql, connect_database


class PostgreSQLTranslationTests(unittest.TestCase):
    def test_bind_parameters_and_preserve_string_literals(self):
        sql = postgres_sql("SELECT * FROM users WHERE loginId=? AND name='testUser'")
        self.assertIn('"loginId"=%s', sql)
        self.assertIn("'testUser'", sql)

    def test_sqlite_double_quoted_active_literal(self):
        sql = postgres_sql('SELECT * FROM users WHERE accountStatus="ACTIVE"')
        self.assertIn('"accountStatus"=\'ACTIVE\'', sql)

    def test_mixed_case_identifiers(self):
        sql = postgres_sql("SELECT teamId, userId FROM teamMembers WHERE createdAt=?")
        self.assertIn('"teamId"', sql)
        self.assertIn('"userId"', sql)
        self.assertIn('"teamMembers"', sql)
        self.assertIn('"createdAt"=%s', sql)

    def test_identity_column_conversion(self):
        sql = postgres_sql("id INTEGER PRIMARY KEY AUTOINCREMENT")
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", sql)

    def test_reject_invalid_database_url(self):
        with self.assertRaises(RuntimeError):
            connect_database(":memory:", "sqlite:///unexpected")


if __name__ == "__main__":
    unittest.main()
